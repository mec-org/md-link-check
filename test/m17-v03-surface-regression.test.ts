/**
 * M17 — frozen v0.3 action surface regression.
 *
 * Each test compares one covered surface with committed expected bytes captured
 * before any GitHub Actions job summary existed: human-readable CLI output,
 * JSON CLI output, workflow-command annotations (including escaping and
 * truncation), `GITHUB_OUTPUT` records, exit codes and stdout/stderr routing.
 * M20 adds the job summary itself; its test here proves the summary is appended
 * without changing any frozen v0.3 byte, and
 * `test/action-summary-integration.test.ts` covers the new bytes.
 * The expected files are checked in rather than regenerated by the formatters
 * under test, and `manifest.json` records the v0.3.0 tag provenance and every
 * expected file's SHA-256.
 */
import { createHash } from 'node:crypto';
import { cpSync, existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { formatAnnotations } from '../src/annotation.js';
import { REPO_ROOT, runAction, runCli } from './action-helpers.js';
import { makeTempRoot, writeFiles } from './helpers.js';
import { M11_SPECIAL_VALUES_FIXTURE, parseAnnotation } from './m11-helpers.js';
import {
  annotationLineCount,
  createOutputPath,
  outputNamesIn,
  parseSummaryOutputs,
  splitActionOutput,
} from './m15-helpers.js';
import { stageFixture } from './m16-helpers.js';
import {
  M17_ACTION_INPUT_ERROR_STDERR,
  M17_ACTION_OUTPUTS,
  M17_ACTION_STDOUT,
  M17_ANNOTATIONS,
  M17_CLI_JSON,
  M17_CLI_TEXT,
  M17_CLI_USAGE_STDERR,
  M17_EDGE_ANNOTATIONS,
  M17_EDGE_FINDINGS,
  M17_EXIT_CODE,
  M17_FINDINGS,
  M17_FIXTURE_DIR,
  M17_MANIFEST_PATH,
  M17_SPECIAL_ANNOTATIONS,
  M17_SUMMARY,
  runM17Action,
} from './m17-helpers.js';

/** The subset of the version 1 JSON document these tests compare. */
interface FrozenJsonReport {
  summary: {
    filesChecked: number;
    broken: number;
    externalSkipped: number;
  };
  diagnostics: Array<{
    file: string;
    line: number;
    target: string;
    reason: string;
  }>;
}

/** The checked-in provenance manifest for the expected-byte directory. */
interface FixtureManifest {
  readonly surface: string;
  readonly source: {
    readonly tag: string;
    readonly tagObject: string;
    readonly commit: string;
    readonly actionBundleSha256: string;
  };
  readonly capture: {
    readonly script: string;
    readonly fixture: string;
  };
  readonly files: Record<string, { readonly bytes: number; readonly sha256: string }>;
}

describe('M17 frozen v0.3 CLI surface', () => {
  it('human-readable CLI stdout is byte-for-byte v0.3', async () => {
    const fixture = stageFixture(makeTempRoot());
    const result = await runCli(['--', '.'], { cwd: fixture });

    expect(result.status).toBe(M17_EXIT_CODE);
    expect(result.stderr).toBe('');
    expect(result.stdout).toBe(M17_CLI_TEXT);
  });

  it('JSON CLI stdout is byte-for-byte v0.3', async () => {
    const fixture = stageFixture(makeTempRoot());
    const result = await runCli(['--json', '--', '.'], { cwd: fixture });
    const report = JSON.parse(result.stdout) as FrozenJsonReport;

    expect(result.status).toBe(M17_EXIT_CODE);
    expect(result.stderr).toBe('');
    expect(result.stdout).toBe(M17_CLI_JSON);
    expect(report.summary).toEqual(M17_SUMMARY);
    expect(
      report.diagnostics.map(({ file, line, target, reason }) => ({
        file,
        line,
        target,
        reason,
      })),
    ).toEqual(M17_FINDINGS);
  });
});

describe('M17 frozen v0.3 action surface', () => {
  it('action annotations are byte-for-byte v0.3 and in result order', async () => {
    const root = makeTempRoot();
    const fixture = stageFixture(root);
    const outputPath = createOutputPath(root);
    const result = await runM17Action({ cwd: fixture, outputPath });

    expect(result.status).toBe(M17_EXIT_CODE);
    expect(result.stderr).toBe('');
    expect(result.stdout).toBe(M17_ACTION_STDOUT);
    expect(result.stdout.slice(0, M17_CLI_TEXT.length)).toBe(M17_CLI_TEXT);

    const annotations = result.stdout.slice(M17_CLI_TEXT.length);
    expect(annotations).toBe(M17_ANNOTATIONS);
    expect(annotationLineCount(result.stdout)).toBe(M17_FINDINGS.length);

    const parsed = annotations
      .split('\n')
      .filter((line) => line !== '')
      .map(parseAnnotation);
    expect(
      parsed.map(({ file, line, message }) => ({ file, line, message })),
    ).toEqual(
      M17_FINDINGS.map((finding) => ({
        file: finding.file,
        line: finding.line,
        message: `${finding.target} — ${finding.reason}`,
      })),
    );
  });

  it('summary-count outputs are byte-for-byte v0.3 and in order', async () => {
    const root = makeTempRoot();
    const fixture = stageFixture(root);
    const outputPath = createOutputPath(root);
    const result = await runM17Action({ cwd: fixture, outputPath });
    const outputBytes = readFileSync(outputPath, 'utf8');

    expect(result.status).toBe(M17_EXIT_CODE);
    expect(outputBytes).toBe(M17_ACTION_OUTPUTS);
    expect(outputNamesIn(outputBytes)).toEqual([
      'files-checked',
      'broken',
      'external-skipped',
    ]);
    expect(parseSummaryOutputs(outputBytes)).toEqual(M17_SUMMARY);
  });

  it('action annotations escape special values from v0.3', async () => {
    const root = makeTempRoot();
    const fixture = join(root, 'special');
    cpSync(M11_SPECIAL_VALUES_FIXTURE, fixture, { recursive: true });
    const outputPath = createOutputPath(root);
    const result = await runM17Action({ cwd: fixture, outputPath });
    const expectedLines = M17_SPECIAL_ANNOTATIONS.split('\n').filter(
      (line) => line !== '',
    );
    const { annotations } = splitActionOutput(result.stdout, expectedLines.length);

    expect(result.status).toBe(M17_EXIT_CODE);
    expect(result.stderr).toBe('');
    expect(annotations).toEqual(expectedLines);
    expect(`${annotations.join('\n')}\n`).toBe(M17_SPECIAL_ANNOTATIONS);
    expect(annotationLineCount(result.stdout)).toBe(expectedLines.length);
  });

  it('annotation escaping and truncation bytes are frozen from v0.3', () => {
    const actual = formatAnnotations(M17_EDGE_FINDINGS)
      .map((annotation) => `${annotation}\n`)
      .join('');

    expect(actual).toBe(M17_EDGE_ANNOTATIONS);
  });

  it('exit behavior is unchanged', async () => {
    const root = makeTempRoot();
    const fixture = stageFixture(root);
    const broken = await runM17Action({
      cwd: fixture,
      outputPath: createOutputPath(root),
    });
    expect(broken.status).toBe(1);
    expect(broken.stderr).toBe('');

    const cleanRoot = makeTempRoot();
    writeFiles(cleanRoot, { 'README.md': '# Clean fixture\n' });
    const cleanCli = await runCli(['--', '.'], { cwd: cleanRoot });
    const cleanAction = await runM17Action({
      cwd: cleanRoot,
      outputPath: createOutputPath(cleanRoot),
    });
    expect(cleanCli.status).toBe(0);
    expect(cleanCli.stderr).toBe('');
    expect(cleanCli.stdout).toBe(
      'Checked 1 file: 0 broken targets, 0 external links skipped.\n',
    );
    expect(cleanAction.status).toBe(0);
    expect(cleanAction.stderr).toBe('');
    expect(annotationLineCount(cleanAction.stdout)).toBe(0);

    const usageRoot = makeTempRoot();
    writeFiles(usageRoot, { 'README.md': '# Usage fixture\n' });
    const usageOutput = createOutputPath(usageRoot, 'keep=sentinel\n');
    const usageCli = await runCli([], { cwd: usageRoot });
    const usageAction = await runAction({
      cwd: usageRoot,
      inputs: { INPUT_PATHS: '.', INPUT_EXTERNAL: 'maybe' },
      env: { GITHUB_OUTPUT: usageOutput },
    });
    expect(usageCli.status).toBe(2);
    expect(usageCli.stdout).toBe('');
    expect(usageCli.stderr).toBe(M17_CLI_USAGE_STDERR);
    expect(usageAction.status).toBe(2);
    expect(usageAction.stdout).toBe('');
    expect(usageAction.stderr).toBe(M17_ACTION_INPUT_ERROR_STDERR);
    expect(annotationLineCount(usageAction.stdout)).toBe(0);
    expect(readFileSync(usageOutput, 'utf8')).toBe('keep=sentinel\n');
  });

  it('M20 appends one job summary without changing the frozen v0.3 surfaces', async () => {
    const root = makeTempRoot();
    const fixture = stageFixture(root);
    const summaryPath = join(root, 'step-summary.md');
    writeFileSync(summaryPath, 'sentinel\n');
    const outputPath = createOutputPath(root);
    const broken = await runM17Action({
      cwd: fixture,
      outputPath,
      stepSummaryPath: summaryPath,
    });

    // Every frozen v0.3 surface stays byte-for-byte unchanged: the CLI output,
    // the annotations that follow it, stderr, the exit code and the outputs.
    expect(broken.status).toBe(M17_EXIT_CODE);
    expect(broken.stdout).toBe(M17_ACTION_STDOUT);
    expect(broken.stderr).toBe('');
    expect(readFileSync(outputPath, 'utf8')).toBe(M17_ACTION_OUTPUTS);
    expect(broken.stdout).not.toContain('## Results');

    // M20 appends exactly one M19-formatted summary after the existing bytes,
    // carrying the authentic M17 counts and findings.
    const summary = readFileSync(summaryPath, 'utf8');
    expect(summary.startsWith('sentinel\n## Results\n')).toBe(true);
    expect(summary.split('## Results')).toHaveLength(2);
    expect(summary).toContain(
      '- Checked: 4\n- Broken: 16\n- External skipped: 4\n',
    );
    expect(summary).toContain(
      '- README.md:3: docs/missing.md — target does not exist\n',
    );
    expect(summary.endsWith('\n')).toBe(true);
  });
});

describe('M17 frozen fixture provenance', () => {
  it('expected bytes match the recorded v0.3.0 tag manifest', () => {
    const manifest = JSON.parse(
      readFileSync(M17_MANIFEST_PATH, 'utf8'),
    ) as FixtureManifest;

    expect(manifest.surface).toBe('v0.3.0');
    expect(manifest.source.tag).toBe('v0.3.0');
    expect(manifest.source.tagObject).toMatch(/^[0-9a-f]{40}$/);
    expect(manifest.source.commit).toMatch(/^[0-9a-f]{40}$/);
    expect(manifest.source.actionBundleSha256).toMatch(/^[0-9a-f]{64}$/);
    expect(manifest.capture.script).toBe('test/m17-capture-fixtures.mjs');
    expect(manifest.capture.fixture).toBe('test/fixtures/m16-multifile');
    expect(existsSync(join(REPO_ROOT, manifest.capture.script))).toBe(true);

    const expectedNames = readdirSync(M17_FIXTURE_DIR)
      .filter((name) => name !== 'manifest.json')
      .sort();
    expect(Object.keys(manifest.files).sort()).toEqual(expectedNames);

    for (const [name, record] of Object.entries(manifest.files)) {
      const bytes = readFileSync(join(M17_FIXTURE_DIR, name));
      expect(bytes.length, name).toBe(record.bytes);
      expect(createHash('sha256').update(bytes).digest('hex'), name).toBe(
        record.sha256,
      );
    }
  });
});
