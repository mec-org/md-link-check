/**
 * M21 — exit, usage and write-failure interaction.
 *
 * The action's established result is authoritative while the job summary is
 * active: a clean run exits 0, a broken run exits 1, and a usage or
 * action-input error exits 2. A usable destination appends exactly one summary
 * for a completed check (M19 formatter) or exactly one fixed zero-diagnostic
 * usage fragment. An unset, empty or unwritable destination appends nothing,
 * emits exactly one fixed workflow-command warning, and leaves the underlying
 * result, usage text, diagnostics, annotations and outputs byte-for-byte
 * unchanged.
 *
 * These tests exercise the real committed action bundle in a child process for
 * the customer-visible bytes. The expected summaries, usage text and warning
 * lines below are independent hard-coded oracles; none is generated by calling
 * a production formatter.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { appendStepSummary } from '../src/action-step-summary.js';
import { formatWarningCommand } from '../src/annotation.js';
import { runAction, runActionBuild, type ProcessResult } from './action-helpers.js';
import { makeTempRoot, writeFiles } from './helpers.js';

/** A clean fixture: two files, every target resolvable, no external uses. */
const CLEAN_FIXTURE_FILES = {
  'README.md': '# Clean fixture\n\n[guide](docs/guide.md)\n',
  'docs/guide.md': '# Guide\n\n[back](../README.md)\n',
} as const;

/** A broken fixture with one local finding and one skipped external use. */
const BROKEN_FIXTURE_FILES = {
  'README.md':
    '# Broken fixture\n\n' +
    '[missing](missing.md)\n' +
    '[external](https://example.com/)\n',
} as const;

/** The untouched clean CLI stdout. */
const CLEAN_CLI_TEXT =
  'Checked 2 files: 0 broken targets, 0 external links skipped.\n';

/** The untouched broken CLI stdout: diagnostics, then the summary line. */
const BROKEN_CLI_TEXT = [
  'README.md:3: missing.md — target does not exist',
  'Checked 1 file: 1 broken target, 1 external link skipped.',
  '',
].join('\n');

/** The unchanged workflow-command annotation for the broken fixture. */
const BROKEN_ANNOTATION =
  '::error file=README.md,line=3::missing.md — target does not exist\n';

/** The broken action's complete stdout: unchanged CLI text, then annotations. */
const BROKEN_STDOUT = `${BROKEN_CLI_TEXT}${BROKEN_ANNOTATION}`;

/** Independent hard-coded clean summary, including the final newline. */
const CLEAN_SUMMARY = [
  '## Results',
  '',
  '- Checked: 2',
  '- Broken: 0',
  '- External skipped: 0',
  '',
].join('\n');

/** Independent hard-coded broken summary, including the final newline. */
const BROKEN_SUMMARY = [
  '## Results',
  '',
  '- Checked: 1',
  '- Broken: 1',
  '- External skipped: 1',
  '',
  '## Diagnostics',
  '',
  '- README.md:3: missing.md — target does not exist',
  '',
].join('\n');

/** The fixed M21 usage-error summary, including the final newline. */
const USAGE_SUMMARY = [
  '## Results',
  '',
  '- Outcome: usage error',
  '- Link check: not performed',
  '',
].join('\n');

/** Exact clean action outputs. */
const CLEAN_OUTPUTS = 'files-checked=2\nbroken=0\nexternal-skipped=0\n';

/** Exact broken action outputs. */
const BROKEN_OUTPUTS = 'files-checked=1\nbroken=1\nexternal-skipped=1\n';

/** Exact established action-input usage diagnostic. */
const ACTION_INPUT_USAGE_TEXT = [
  'md-link-check: invalid action input "external": expected "true" or "false"',
  '',
  'Usage: md-link-check [--json] [--external] <path...>',
  'Run "md-link-check --help" for usage and exit codes.',
  '',
].join('\n');

/** Exact established CLI usage diagnostic for an empty `paths` input. */
const NO_PATHS_USAGE_TEXT = [
  'md-link-check: no input paths',
  '',
  'Usage: md-link-check [--json] [--external] <path...>',
  'Run "md-link-check --help" for usage and exit codes.',
  '',
].join('\n');

/** The exact warning for an unset or empty destination. */
const UNAVAILABLE_WARNING =
  '::warning::GITHUB_STEP_SUMMARY is not set; no job summary was written.\n';

/** The exact warning for a destination that rejects the append. */
const WRITE_FAILED_WARNING =
  '::warning::GITHUB_STEP_SUMMARY could not be written; no job summary was written.\n';

interface Invocation {
  readonly result: ProcessResult;
  readonly outputPath: string;
}

interface InvocationOptions {
  readonly root: string;
  readonly fixture: string;
  /** A path, the empty string, or `undefined` for an absent variable. */
  readonly summaryPath: string | undefined;
  readonly inputs?: Record<string, string | undefined>;
  readonly outputSeed?: string;
}

/**
 * Runs the committed action bundle exactly as the hosted runner does. The
 * summary variable is always an explicit own property: `undefined` omits the
 * variable, `''` sets it empty, and any other value is the destination path.
 */
async function invoke(options: InvocationOptions): Promise<Invocation> {
  const outputPath = join(options.root, 'github-output.txt');
  writeFileSync(outputPath, options.outputSeed ?? '');
  const result = await runAction({
    cwd: options.fixture,
    inputs: {
      INPUT_PATHS: '.',
      INPUT_EXTERNAL: 'false',
      ...options.inputs,
    },
    env: {
      GITHUB_OUTPUT: outputPath,
      GITHUB_STEP_SUMMARY: options.summaryPath,
    },
  });
  return { result, outputPath };
}

/** Exact complete warning lines in one captured stream. */
function warningLines(text: string): string[] {
  return text.split('\n').filter((line) => line.startsWith('::warning::'));
}

/** Occurs exactly once when one summary fragment was appended once. */
function summaryOccurrences(summary: string): number {
  return summary.split('## Results').length - 1;
}

describe('M21 exit and usage interaction with a writable summary', () => {
  it('keeps exit zero when a clean summary is written', async () => {
    const root = makeTempRoot();
    const fixture = join(root, 'fixture');
    writeFiles(fixture, CLEAN_FIXTURE_FILES);
    const summaryPath = join(root, 'step-summary.md');
    writeFileSync(summaryPath, '');

    const { result, outputPath } = await invoke({ root, fixture, summaryPath });

    // The established surfaces are byte-for-byte unchanged.
    expect(result.timedOut).toBe(false);
    expect(result.status).toBe(0);
    expect(result.stdout).toBe(CLEAN_CLI_TEXT);
    expect(result.stderr).toBe('');
    expect(readFileSync(outputPath, 'utf8')).toBe(CLEAN_OUTPUTS);
    expect(warningLines(`${result.stdout}${result.stderr}`)).toEqual([]);

    // Exactly one complete M19 summary was appended.
    const summary = readFileSync(summaryPath, 'utf8');
    expect(summary).toBe(CLEAN_SUMMARY);
    expect(summaryOccurrences(summary)).toBe(1);
  });

  it('keeps exit one when a broken summary is written', async () => {
    const root = makeTempRoot();
    const fixture = join(root, 'fixture');
    writeFiles(fixture, BROKEN_FIXTURE_FILES);
    const summaryPath = join(root, 'step-summary.md');
    writeFileSync(summaryPath, '');

    const { result, outputPath } = await invoke({ root, fixture, summaryPath });

    // Diagnostics, annotation, outputs and exit keep their exact bytes and
    // order; a successful summary adds no warning and no printed bytes.
    expect(result.timedOut).toBe(false);
    expect(result.status).toBe(1);
    expect(result.stdout).toBe(BROKEN_STDOUT);
    expect(result.stderr).toBe('');
    expect(readFileSync(outputPath, 'utf8')).toBe(BROKEN_OUTPUTS);
    expect(warningLines(`${result.stdout}${result.stderr}`)).toEqual([]);

    const summary = readFileSync(summaryPath, 'utf8');
    expect(summary).toBe(BROKEN_SUMMARY);
    expect(summaryOccurrences(summary)).toBe(1);
  });

  it('keeps exit two and writes a diagnostic-free usage summary', async () => {
    // An action-input error exits before any check starts.
    const inputRoot = makeTempRoot();
    const inputFixture = join(inputRoot, 'fixture');
    writeFiles(inputFixture, CLEAN_FIXTURE_FILES);
    const inputSummaryPath = join(inputRoot, 'step-summary.md');
    writeFileSync(inputSummaryPath, '');
    const inputFailure = await invoke({
      root: inputRoot,
      fixture: inputFixture,
      summaryPath: inputSummaryPath,
      inputs: { INPUT_EXTERNAL: 'maybe' },
    });

    expect(inputFailure.result.timedOut).toBe(false);
    expect(inputFailure.result.status).toBe(2);
    expect(inputFailure.result.stdout).toBe('');
    expect(inputFailure.result.stderr).toBe(ACTION_INPUT_USAGE_TEXT);
    expect(readFileSync(inputFailure.outputPath, 'utf8')).toBe('');
    expect(warningLines(inputFailure.result.stdout)).toEqual([]);

    const inputSummary = readFileSync(inputSummaryPath, 'utf8');
    expect(inputSummary).toBe(USAGE_SUMMARY);
    expect(summaryOccurrences(inputSummary)).toBe(1);
    expect(inputSummary).not.toContain('## Diagnostics');
    expect(
      inputSummary.split('\n').filter((line) => line.startsWith('- ')),
    ).toEqual(['- Outcome: usage error', '- Link check: not performed']);

    // A CLI usage error reached through the real action path behaves the same:
    // empty `paths` yields the established "no input paths" usage diagnostic.
    const cliRoot = makeTempRoot();
    const cliFixture = join(cliRoot, 'fixture');
    writeFiles(cliFixture, CLEAN_FIXTURE_FILES);
    const cliSummaryPath = join(cliRoot, 'step-summary.md');
    writeFileSync(cliSummaryPath, '');
    const cliUsage = await invoke({
      root: cliRoot,
      fixture: cliFixture,
      summaryPath: cliSummaryPath,
      inputs: { INPUT_PATHS: '' },
    });

    expect(cliUsage.result.status).toBe(2);
    expect(cliUsage.result.stdout).toBe('');
    expect(cliUsage.result.stderr).toBe(NO_PATHS_USAGE_TEXT);
    expect(warningLines(cliUsage.result.stdout)).toEqual([]);
    expect(readFileSync(cliSummaryPath, 'utf8')).toBe(USAGE_SUMMARY);
  });
});

describe('M21 unavailable summary destinations', () => {
  it('encodes both fixed warnings through the workflow-command data channel', () => {
    // The one warning emitter uses the established data-channel escaping, so a
    // message cannot terminate the command or inject a second workflow command.
    const prefix = '::warning::';
    expect(
      formatWarningCommand(UNAVAILABLE_WARNING.slice(prefix.length, -1)),
    ).toBe(UNAVAILABLE_WARNING.slice(0, -1));
    expect(
      formatWarningCommand(WRITE_FAILED_WARNING.slice(prefix.length, -1)),
    ).toBe(WRITE_FAILED_WARNING.slice(0, -1));
    expect(formatWarningCommand('50% done\r\nnext')).toBe(
      '::warning::50%25 done%0D%0Anext',
    );
  });

  it('warns once for an unset summary destination without changing exit zero', async () => {
    const root = makeTempRoot();
    const fixture = join(root, 'fixture');
    writeFiles(fixture, CLEAN_FIXTURE_FILES);

    const { result, outputPath } = await invoke({
      root,
      fixture,
      summaryPath: undefined,
    });

    // The only added byte is the fixed warning, once, after all CLI output.
    expect(result.timedOut).toBe(false);
    expect(result.status).toBe(0);
    expect(result.stdout).toBe(`${CLEAN_CLI_TEXT}${UNAVAILABLE_WARNING}`);
    expect(warningLines(result.stdout)).toEqual([UNAVAILABLE_WARNING.slice(0, -1)]);
    expect(result.stderr).toBe('');
    expect(readFileSync(outputPath, 'utf8')).toBe(CLEAN_OUTPUTS);
    expect(result.stdout.endsWith(UNAVAILABLE_WARNING)).toBe(true);
  });

  it('warns once for an unset summary destination without changing exit one', async () => {
    const root = makeTempRoot();
    const fixture = join(root, 'fixture');
    writeFiles(fixture, BROKEN_FIXTURE_FILES);

    const { result, outputPath } = await invoke({
      root,
      fixture,
      summaryPath: undefined,
    });

    // Every established byte of the broken run remains unchanged and in order.
    expect(result.status).toBe(1);
    expect(result.stdout).toBe(`${BROKEN_STDOUT}${UNAVAILABLE_WARNING}`);
    expect(warningLines(result.stdout)).toEqual([UNAVAILABLE_WARNING.slice(0, -1)]);
    expect(result.stderr).toBe('');
    expect(readFileSync(outputPath, 'utf8')).toBe(BROKEN_OUTPUTS);
  });

  it('warns once for an unset summary destination without changing exit two', async () => {
    const root = makeTempRoot();
    const fixture = join(root, 'fixture');
    writeFiles(fixture, CLEAN_FIXTURE_FILES);

    const { result, outputPath } = await invoke({
      root,
      fixture,
      summaryPath: undefined,
      inputs: { INPUT_EXTERNAL: 'maybe' },
      outputSeed: 'keep=sentinel\n',
    });

    // The usage text is byte-for-byte unchanged; the warning is the only added
    // byte from M21 and does not become an annotation or a published output.
    expect(result.timedOut).toBe(false);
    expect(result.status).toBe(2);
    expect(result.stdout).toBe(UNAVAILABLE_WARNING);
    expect(warningLines(result.stdout)).toEqual([UNAVAILABLE_WARNING.slice(0, -1)]);
    expect(result.stderr).toBe(ACTION_INPUT_USAGE_TEXT);
    expect(readFileSync(outputPath, 'utf8')).toBe('keep=sentinel\n');
  });

  it('warns once for an empty summary destination', async () => {
    const root = makeTempRoot();
    const fixture = join(root, 'fixture');
    writeFiles(fixture, BROKEN_FIXTURE_FILES);

    const { result, outputPath } = await invoke({
      root,
      fixture,
      summaryPath: '',
    });

    // The empty string is unavailable exactly like an unset variable: no filesystem
    // access can be attempted, the same single warning is emitted, and the
    // broken result keeps its exit and bytes.
    expect(result.timedOut).toBe(false);
    expect(result.status).toBe(1);
    expect(result.stdout).toBe(`${BROKEN_STDOUT}${UNAVAILABLE_WARNING}`);
    expect(warningLines(result.stdout)).toEqual([UNAVAILABLE_WARNING.slice(0, -1)]);
    expect(result.stderr).toBe('');
    expect(readFileSync(outputPath, 'utf8')).toBe(BROKEN_OUTPUTS);
  });

  it('warns once for an unwritable summary destination without replacing the result', async () => {
    // A path under a missing parent is a deterministic ENOENT on every platform.
    const brokenRoot = makeTempRoot();
    const brokenFixture = join(brokenRoot, 'fixture');
    writeFiles(brokenFixture, BROKEN_FIXTURE_FILES);
    const brokenDestination = join(brokenRoot, 'missing-parent', 'step-summary.md');

    const broken = await invoke({
      root: brokenRoot,
      fixture: brokenFixture,
      summaryPath: brokenDestination,
    });

    expect(broken.result.timedOut).toBe(false);
    expect(broken.result.status).toBe(1);
    expect(broken.result.stdout).toBe(`${BROKEN_STDOUT}${WRITE_FAILED_WARNING}`);
    expect(warningLines(broken.result.stdout)).toEqual([
      WRITE_FAILED_WARNING.slice(0, -1),
    ]);
    expect(broken.result.stderr).toBe('');
    expect(readFileSync(broken.outputPath, 'utf8')).toBe(BROKEN_OUTPUTS);
    expect(broken.result.stdout).not.toContain('internal error');
    expect(broken.result.stderr).not.toMatch(/^\s+at /m);
    expect(existsSync(brokenDestination)).toBe(false);

    // A usage result is equally protected: exit 2 and its usage text survive.
    const usageRoot = makeTempRoot();
    const usageFixture = join(usageRoot, 'fixture');
    writeFiles(usageFixture, CLEAN_FIXTURE_FILES);
    const usageDestination = join(usageRoot, 'missing-parent', 'step-summary.md');

    const usage = await invoke({
      root: usageRoot,
      fixture: usageFixture,
      summaryPath: usageDestination,
      inputs: { INPUT_EXTERNAL: 'maybe' },
    });

    expect(usage.result.status).toBe(2);
    expect(usage.result.stdout).toBe(WRITE_FAILED_WARNING);
    expect(warningLines(usage.result.stdout)).toEqual([
      WRITE_FAILED_WARNING.slice(0, -1),
    ]);
    expect(usage.result.stderr).toBe(ACTION_INPUT_USAGE_TEXT);
    expect(existsSync(usageDestination)).toBe(false);
  });

  it('does not duplicate warnings when summary append fails', async () => {
    const root = makeTempRoot();
    const destination = join(root, 'missing-parent', 'step-summary.md');

    // The low-level append classifies its own failure without printing one.
    await expect(appendStepSummary(destination, 'probe')).resolves.toBe('failed');
    expect(existsSync(destination)).toBe(false);

    // The action wrapper then reports exactly one warning for that same failure;
    // there is no second low-level or wrapper warning, on either stream.
    const fixture = join(root, 'fixture');
    writeFiles(fixture, BROKEN_FIXTURE_FILES);
    const { result } = await invoke({ root, fixture, summaryPath: destination });

    expect(result.status).toBe(1);
    expect(warningLines(result.stdout)).toEqual([WRITE_FAILED_WARNING.slice(0, -1)]);
    expect(warningLines(result.stderr)).toEqual([]);
    expect(result.stdout.match(/::warning::/g)).toHaveLength(1);
    expect(`${result.stdout}${result.stderr}`.match(/::warning::/g)).toHaveLength(1);
  });

  it('action-dist/index.cjs is current', async () => {
    // The M21 warning and usage-summary code reaches the shipped artifact; the
    // repository's established build script proves the committed bytes equal a
    // fresh build of the current sources.
    const result = await runActionBuild(['--check']);

    expect(result.status, result.stderr).toBe(0);
    expect(result.stderr).toBe('');
    expect(result.stdout).toContain(
      'action entrypoint is reproducible: action-dist/index.cjs',
    );
  });
});
